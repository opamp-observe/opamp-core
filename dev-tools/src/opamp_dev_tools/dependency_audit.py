"""Audit one uv-locked Python project for the OpAMP developer CLI."""

from __future__ import annotations

import argparse
import logging
import shutil
import subprocess
import sys
import tempfile
from collections.abc import Sequence
from pathlib import Path

ARGUMENT_PROJECT = "--project"
AUDIT_REQUIREMENTS_FILE = "audit-requirements.txt"
DEFAULT_LOG_FORMAT = "%(asctime)s %(levelname)s %(name)s %(message)s"
LOGGER = logging.getLogger(__name__)
PIP_AUDIT_MODULE = "pip_audit"
UV_EXECUTABLE = "uv"


def audit_locked_project(project_path: Path, *, logger: logging.Logger = LOGGER) -> int:
    """Export and audit one project's complete locked dependency graph.

    Parameters:
        project_path: Directory containing the project's ``pyproject.toml`` and ``uv.lock``.
        logger: Logger receiving debug details about the generated commands.

    Returns:
        The pip-audit exit code, or a command-error exit code when export cannot start.
    """

    resolved_project_path = project_path.resolve()
    uv_path = shutil.which(UV_EXECUTABLE)
    if uv_path is None:
        logger.error("uv is required to export locked dependency graphs")
        return 2

    with tempfile.TemporaryDirectory(prefix="opamp-pip-audit-") as temporary_directory:
        requirements_path = Path(temporary_directory) / AUDIT_REQUIREMENTS_FILE
        export_command = _build_export_command(
            uv_path=uv_path,
            project_path=resolved_project_path,
            requirements_path=requirements_path,
        )
        logger.debug("exporting dependency graph command=%s", export_command)
        export_result = _run_command(export_command, logger=logger)
        if export_result != 0:
            return export_result

        audit_command = _build_audit_command(requirements_path=requirements_path)
        logger.debug("auditing dependency graph command=%s", audit_command)
        return _run_command(audit_command, logger=logger)


def _build_export_command(
    *,
    uv_path: str,
    project_path: Path,
    requirements_path: Path,
) -> list[str]:
    """Build the uv command that produces pinned audit input.

    Parameters:
        uv_path: Resolved uv executable path.
        project_path: Project directory whose lock file is exported.
        requirements_path: Temporary requirements output path.
    """

    return [
        uv_path,
        "--quiet",
        "export",
        "--project",
        str(project_path),
        "--locked",
        "--all-extras",
        "--no-hashes",
        "--no-emit-project",
        "--no-emit-workspace",
        "--no-emit-local",
        "--output-file",
        str(requirements_path),
    ]


def _build_audit_command(*, requirements_path: Path) -> list[str]:
    """Build the pip-audit command for one exported requirements file.

    Parameters:
        requirements_path: Pinned requirements file generated by uv.
    """

    return [
        sys.executable,
        "-m",
        PIP_AUDIT_MODULE,
        "--strict",
        "--requirement",
        str(requirements_path),
    ]


def _run_command(command: list[str], *, logger: logging.Logger) -> int:
    """Run one dependency-audit command with inherited console streams.

    Parameters:
        command: Argument vector executed without a shell.
        logger: Logger receiving startup failures.

    Returns:
        The child exit code, or ``2`` when the executable cannot be started.
    """

    try:
        completed_process = subprocess.run(command, check=False)  # noqa: S603
    except OSError as error:
        logger.error("unable to execute dependency audit command: %s", error)
        return 2
    return int(completed_process.returncode)


def _build_parser() -> argparse.ArgumentParser:
    """Create the command-line parser for a single-project audit."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        ARGUMENT_PROJECT,
        required=True,
        type=Path,
        help="Python project directory containing a uv.lock file",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    """Parse command-line arguments and audit the selected locked project.

    Parameters:
        argv: Optional arguments used by tests; defaults to process arguments.
    """

    logging.basicConfig(level=logging.DEBUG, format=DEFAULT_LOG_FORMAT)
    arguments = _build_parser().parse_args(argv)
    return audit_locked_project(arguments.project)


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
